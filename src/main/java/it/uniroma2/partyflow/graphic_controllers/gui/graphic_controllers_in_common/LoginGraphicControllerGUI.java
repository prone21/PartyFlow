package it.uniroma2.partyflow.graphic_controllers.gui.graphic_controllers_in_common;

import it.uniroma2.partyflow.app_controllers.LoginController;
import it.uniroma2.partyflow.beans.LoginCredentialsBean;
import it.uniroma2.partyflow.enums.AccountType;
import it.uniroma2.partyflow.errorhandlers.handlerui.HandlerJavaFxGUIError;
import it.uniroma2.partyflow.errorhandlers.HandlerSystemError;
import it.uniroma2.partyflow.exceptions.systemexception.InternalException;
import it.uniroma2.partyflow.exceptions.uiexception.ApplicationException;
import it.uniroma2.partyflow.exceptions.uiexception.RequiredFieldException;
import it.uniroma2.partyflow.utilities.navigators.GUINavigatorSingleton;
import javafx.fxml.FXML;
import javafx.scene.control.TextField;

import static it.uniroma2.partyflow.enums.UserField.EMAIL;
import static it.uniroma2.partyflow.enums.UserField.PASSWORD;


/**
 * Graphic controller responsible for managing the JavaFX login view.
 *
 * <p>Collects user credentials from the login form, initializes a
 * LoginCredentialsBean to perform syntactic checks, and delegates
 * user authentication to LoginController.</p>
 *
 * <p>Manages navigation between views and delegates error handling
 * to HandlerJavaFxGUIError and HandlerSystemError.</p>
 */


public class LoginGraphicControllerGUI {
     @FXML
     private TextField emailField;
     @FXML
     private TextField pwdField;

    /**
     * Handles the authentication request generated by the login button.
     *
     * <p>Collects the user's credentials and populates a
     * LoginCredentialsBean, whose setters perform syntactic checks.</p>
     *
     * <p>Delegates authentication to LoginController and navigates
     * to the appropriate home page based on the returned account type.</p>
     *
     * <p>Handles errors that may occur during authentication by delegating
     * the highlighting of missing fields and the display of error messages
     * to HandlerJavaFxGUIError, while fatal errors are managed by
     * HandlerSystemError.</p>
     */

    @FXML
    public void submitCredentials() {
        try{
            // 0) fetch user data
            String email = emailField.getText();
            String pwd = pwdField.getText();
            //---------------------------------------------

            // 1) create the bean where the user data will be stored
            LoginCredentialsBean loginBean = new LoginCredentialsBean(email,pwd);
            //---------------------------------------------

            // 2) pass the LoginCredentialsBean to the application controller
            LoginController loginController = new LoginController();
            AccountType accountType = loginController.login(loginBean);
            //---------------------------------------------


            // 3) show the right homepage
            GUINavigatorSingleton nav = GUINavigatorSingleton.getInstance();
            switch(accountType){
                case PARTICIPANT:
                    nav.goToView("/it/uniroma2/partyflow/view/Participant/participantHomePage.fxml");
                    break;

                case PARTY_PLANNER:
                    nav.goToView("/it/uniroma2/partyflow/view/Party_Planner/partyPlannerHomePage.fxml");
                    break;
            }
            //---------------------------------------------
        }
        catch (RequiredFieldException e) {
            /*
             * Handles missing required fields in the login form.
             * Uses an if statement to identify the corresponding JavaFX element
             * and delegates its highlighting to the JavaFxGUI error handler.
             */
            HandlerJavaFxGUIError handlerJavaError = HandlerJavaFxGUIError.getInstance();

            if(e.getField() == EMAIL){
                handlerJavaError.highlightMissingFormElement(this.emailField);
            }
            else if(e.getField() == PASSWORD){
                handlerJavaError.highlightMissingFormElement(this.pwdField);
            }

        }
        catch (ApplicationException e){
            HandlerJavaFxGUIError handlerJavaFxGUIError = HandlerJavaFxGUIError.getInstance();
            handlerJavaFxGUIError.errorMessage(e.getMessage());
        }
        catch (InternalException e){
            HandlerSystemError handlerSystemError = HandlerSystemError.getInstance();
            handlerSystemError.logError("Log in failed: " + e.getMessage(), e);

            handlerSystemError.handleFatalError(e);

        }
    }



    /**
     * Navigates from the login view to the registration view
     * through GUINavigatorSingleton.
     *
     * <p>If navigation fails, the resulting exception is logged
     * and handled as a fatal error by HandlerSystemError.</p>
     */

    @FXML
    public void signUp(){
        try {
            GUINavigatorSingleton nav = GUINavigatorSingleton.getInstance();
            nav.goToView("/it/uniroma2/partyflow/view/view_in_common/signUp.fxml");
        }
        catch (InternalException e){
            HandlerSystemError handlerSystemError = HandlerSystemError.getInstance();
            handlerSystemError.logError("Failed to navigate to the sign-up page: " + e.getMessage(), e);

            handlerSystemError.handleFatalError(e);
        }
    }


    /**
     * Displays an alert informing the user that authentication
     * through Google has not been implemented yet.
     */

    @FXML
    public void continueWithGoogle(){
        HandlerJavaFxGUIError handlerJavaError = HandlerJavaFxGUIError.getInstance();
        handlerJavaError.infoMessage("Google log-in is not implemented yet.");
    }



    /**
     * Displays an alert informing the user that authentication
     * through Facebook has not been implemented yet.
     */

    @FXML
    public void continueWithFacebook(){
        HandlerJavaFxGUIError handlerJavaError = HandlerJavaFxGUIError.getInstance();
        handlerJavaError.infoMessage("Facebook log-in is not implemented yet.");
    }


}
