package it.uniroma2.partyflow.graphic_controllers.gui.graphic_controllers_in_common;

import it.uniroma2.partyflow.app_controllers.ProfileController;
import it.uniroma2.partyflow.beans.UserBean;
import it.uniroma2.partyflow.errorhandlers.HandlerSystemError;
import it.uniroma2.partyflow.errorhandlers.handlerui.HandlerJavaFxGUIError;
import it.uniroma2.partyflow.exceptions.systemexception.InternalException;
import it.uniroma2.partyflow.exceptions.uiexception.ApplicationException;
import it.uniroma2.partyflow.exceptions.uiexception.InvalidFieldFormatException;
import it.uniroma2.partyflow.exceptions.uiexception.RequiredFieldException;
import it.uniroma2.partyflow.utilities.navigators.GUINavigatorSingleton;
import javafx.fxml.FXML;
import javafx.scene.control.Label;

/**
 * Graphic controller responsible for managing the JavaFX user profile view.
 *
 * <p>Retrieves the authenticated user's profile information through
 * ProfileController and displays it in the corresponding GUI elements.</p>
 *
 * <p>Handles logout, profile editing and password change requests,
 * delegates navigation to GUINavigatorSingleton, and manages errors
 * through the appropriate error handlers.</p>
 */

public class ProfileGraphicControllerGUI {
    // -----------data labels-----------
    @FXML
    private Label nameLabel;
    @FXML
    private Label surnameLabel;
    @FXML
    private Label emailLabel;
    @FXML
    private Label accountTypeLabel;
    @FXML
    private Label dateOfBirthLabel;
    @FXML
    private Label genderLabel;
    // --------------------------------

    // --------------------------------
    @FXML
    private Label initialsLabel;
    @FXML
    private Label fullNameLabel;
    @FXML
    private Label roleBadgeLabel;
    // --------------------------------

    private final ProfileController profileController =  new ProfileController();

    /**
     * Initializes the profile view with the authenticated user's information.
     *
     * <p>Automatically invoked by the JavaFX FXMLLoader after the FXML
     * components have been injected. Retrieves the user's profile through
     * ProfileController and populates the corresponding labels, including
     * the user's initials, full name and account type.</p>
     *
     * <p>Handles application exceptions by displaying the corresponding
     * error messages. Invalid or missing data retrieved from the persistence
     * layer is logged as a technical error, while a generic error message
     * is displayed to the user.</p>
     */
    @FXML
    public void initialize(){
        try{
            UserBean user = this.profileController.retriveProfile();

            nameLabel.setText(user.getName());
            surnameLabel.setText(user.getSurname());
            emailLabel.setText(user.getEmail());
            accountTypeLabel.setText(user.getAccountType().toString());
            dateOfBirthLabel.setText(user.getDateOfBirth());
            genderLabel.setText(user.getGender().toString());

            initialsLabel.setText(user.getName().substring(0,1).toUpperCase()+
                    user.getSurname().substring(0,1).toUpperCase());
            fullNameLabel.setText(user.getName()+" "+user.getSurname());
            roleBadgeLabel.setText(user.getAccountType().toString());
        }
        catch (ApplicationException e){
            HandlerJavaFxGUIError handlerJavaFxGUIError = HandlerJavaFxGUIError.getInstance();
            handlerJavaFxGUIError.errorMessage(e.getMessage());
        }
        catch (RequiredFieldException | InvalidFieldFormatException e) {
            /*
             * Unlike sign-up, profile data is retrieved from the persistence layer
             * rather than entered directly by the user.
             *
             * Therefore, these exceptions indicate an inconsistency in the retrieved
             * data rather than an invalid user input.
             *
             * The technical error is logged for debugging purposes, while a generic
             * error message is displayed without highlighting any GUI fields.
             */
            HandlerSystemError handlerSystemError = HandlerSystemError.getInstance();
            handlerSystemError.logError("Failed to load profile due to invalid user data: "
                    + e.getMessage(), e);

            HandlerJavaFxGUIError handlerJavaFxGUIError = HandlerJavaFxGUIError.getInstance();
            handlerJavaFxGUIError.errorMessage(
                    "We couldn't load your profile due to an unexpected error. Please try again later."
            );
        }

    }

    /**
     * Handles the logout request generated by the user.
     *
     * <p>Delegates session invalidation to ProfileController and navigates
     * to the application's initial view through GUINavigatorSingleton.</p>
     *
     * <p>If navigation fails, the resulting exception is logged
     * and handled as a fatal error by HandlerSystemError.</p>
     */
    @FXML
    public void logOut(){
        try {
            this.profileController.logOut();
            GUINavigatorSingleton nav = GUINavigatorSingleton.getInstance();
            nav.goToView("/it/uniroma2/partyflow/view/view_in_common/firstScene.fxml");
        }
        catch (InternalException e){
            HandlerSystemError handlerSystemError = HandlerSystemError.getInstance();
            handlerSystemError.logError("Logout failed: unable to navigate to the initial view. "  + e.getMessage(), e);

            handlerSystemError.handleFatalError(e);
        }
    }

    /**
     * Handles the request to edit the user's profile.
     *
     * <p>Currently displays an informational message indicating
     * that the profile editing feature has not been implemented yet.</p>
     */
    @FXML
    public void editProfile(){
        HandlerJavaFxGUIError handlerJavaFxGUIError = HandlerJavaFxGUIError.getInstance();
        handlerJavaFxGUIError.infoMessage("'Edit Profile' feature is not implemented yet.");
    }

    /**
     * Handles the request to change the user's password.
     *
     * <p>Currently displays an informational message indicating
     * that the password change feature has not been implemented yet.</p>
     */
    @FXML
    public void changePassword(){
        HandlerJavaFxGUIError handlerJavaFxGUIError = HandlerJavaFxGUIError.getInstance();
        handlerJavaFxGUIError.infoMessage("'Change Password' feature is not implemented yet.");
    }
}
